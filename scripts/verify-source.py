#!/usr/bin/env python3
"""Verify source AppHost using only UUID-owned local resources."""
import json
import os
from pathlib import Path
import re
import shutil
import time
import socket
import uuid
from infrastructure import ROOT, command, probe, wait_http, free_port

name = 'probe-' + uuid.uuid4().hex[:12]
private_parent = Path(os.environ.get('LOCALAPPDATA', Path.home() / '.local/share')) / 'HaXus/secrets'
secrets = private_parent / name
artifacts = ROOT / '.artifacts/infrastructure' / name
artifacts.mkdir(parents=True)
command(['docker', 'ps', '--format', '{{.ID}}'], log=artifacts / 'engine.log', timeout=15)
probe('prepare', secrets, log=artifacts / 'prepare.log')
cli = ROOT / ('.tools/aspire.cmd' if os.name == 'nt' else '.tools/aspire')
# Copy only AppHost source/project into the ignored UUID workspace, so CLI instance selection cannot target daily development.
apphost_dir = artifacts / 'apphost'
apphost_dir.mkdir()
for filename in ['HaXus.AppHost.csproj', 'AppHost.cs']:
    shutil.copyfile(ROOT / 'aspire/HaXus.AppHost' / filename, apphost_dir / filename)
apphost = apphost_dir / 'HaXus.AppHost.csproj'
(apphost_dir / 'aspire.config.json').write_text(json.dumps({'appHost': {'path': apphost.name}}), encoding='utf-8')
ports = {key: free_port() for key in ['app', 'dashboard', 'otlp', 'resource']}
profile = json.loads((ROOT / 'aspire/HaXus.AppHost/Properties/launchSettings.json').read_text(encoding='utf-8'))
http = profile['profiles']['http']
http['applicationUrl'] = 'http://127.0.0.1:' + str(ports['dashboard'])
http['environmentVariables']['ASPIRE_DASHBOARD_OTLP_ENDPOINT_URL'] = 'http://127.0.0.1:' + str(ports['otlp'])
http['environmentVariables']['ASPIRE_RESOURCE_SERVICE_ENDPOINT_URL'] = 'http://127.0.0.1:' + str(ports['resource'])
(apphost_dir / 'Properties').mkdir()
(apphost_dir / 'Properties/launchSettings.json').write_text(json.dumps(profile), encoding='utf-8')
env = {**os.environ, 'HAXUS_ENVIRONMENT': name, 'HAXUS_SECRET_ROOT': str(secrets),
       'HAXUS_REPOSITORY_ROOT': str(ROOT), 'HAXUS_APP_PORT': str(ports['app'])}
application = 'http://127.0.0.1:' + str(ports['app'])
pid = None
passed = False
try:
    result = command([cli, 'start', '--apphost', apphost, '--format', 'Json', '--non-interactive'],
                     env=env, cwd=apphost_dir, log=secrets / 'source-start.json')
    decoder = json.JSONDecoder()
    metadata = None
    for offset, character in enumerate(result.stdout):
        if character != '{': continue
        try:
            candidate, _ = decoder.raw_decode(result.stdout[offset:])
            if isinstance(candidate, dict) and 'appHostPid' in candidate:
                metadata = candidate; break
        except ValueError: pass
    assert metadata and Path(metadata['appHostPath']).resolve() == apphost.resolve(), 'Detached AppHost identity could not be verified.'
    pid = metadata['appHostPid']
    assert isinstance(pid, int) and pid > 0
    wait_http(application + '/health')
    wait_http(application + '/alive')
    wait_http(application + '/fleet', 404)
    wait_http(application + '/api/hanay/fleet', 404)
    bootstrap_log = secrets / 'openbao/bootstrap.log'
    deadline = time.monotonic() + 240
    while time.monotonic() < deadline and not bootstrap_log.exists(): time.sleep(1)
    assert bootstrap_log.exists(), 'Automatic development OpenBao bootstrap did not finish.'
    records = [json.loads(line) for line in bootstrap_log.read_text(encoding='utf-8').splitlines() if line.startswith('{')]
    assert any(record.get('status') == 'unsealed-development-instance' for record in records), 'Automatic development OpenBao initialization/unseal did not pass.'
    for service, port, route in [('keycloak', '8080/tcp', '/realms/master/.well-known/openid-configuration'),
                                  ('kusa', '5678/tcp', '/healthz/readiness')]:
        container = 'haxus-' + name + '-' + service
        deadline = time.monotonic() + 240
        bindings = None
        while time.monotonic() < deadline:
            inspected = command(['docker', 'container', 'inspect', container, '--format', '{{json .NetworkSettings.Ports}}'], success=False)
            if inspected.returncode == 0:
                bindings = json.loads(inspected.stdout).get(port)
                if bindings: break
            time.sleep(1)
        assert bindings, 'Source supporting-service port was not allocated: ' + service
        wait_http('http://127.0.0.1:' + bindings[0]['HostPort'] + route, timeout=600)
    passed = True
finally:
    if pid:
        command([cli, 'stop', '--apphost', apphost, '--pid', str(pid), '--non-interactive'],
                env=env, cwd=apphost_dir, log=secrets / 'source-stop.log')
    # These names contain the UUID generated by this invocation, never the dev environment.
    assert re.fullmatch(r'probe-[0-9a-f]{12}', name)
    command(['docker', 'ps', '--format', '{{.ID}}'], timeout=15)
    container_names = ['haxus-' + name + '-' + service for service in ['application-db', 'support-db', 'keycloak', 'openbao', 'kusa']]
    for container in container_names:
        identity = command(['docker', 'container', 'inspect', container, '--format', '{{.Name}}'], success=False)
        if identity.returncode != 0 and 'no such container' not in identity.stderr.casefold():
            raise RuntimeError('Cannot verify source-container cleanup while Docker is unavailable.')
        if identity.returncode == 0:
            assert identity.stdout.strip() == '/' + container
            command(['docker', 'rm', '-f', container], log=secrets / (container + '-cleanup.log'))
    for suffix in ['application-db', 'support-db', 'openbao', 'kusa']:
        volume = 'haxus-' + name + '-' + suffix
        identity = command(['docker', 'volume', 'inspect', volume], success=False)
        if identity.returncode == 0: command(['docker', 'volume', 'rm', volume])
        elif 'no such volume' not in identity.stderr.casefold(): raise RuntimeError('Cannot verify source-volume cleanup while Docker is unavailable.')
    deadline = time.monotonic() + 30
    def has_listener(port):
        with socket.socket() as listener:
            listener.settimeout(0.2)
            return listener.connect_ex(('127.0.0.1', port)) == 0
    while time.monotonic() < deadline and any(has_listener(port) for port in ports.values()): time.sleep(1)
    assert not any(has_listener(port) for port in ports.values()), 'A source-verification listener remains after AppHost stop.'
    if passed:
        assert secrets.resolve().parent == private_parent.resolve() and secrets.name == name
        shutil.rmtree(secrets)
if passed:
    (artifacts / 'result.json').write_text(json.dumps({'status': 'passed', 'environment': name,
        'scope': 'Source AppHost, supporting-service startup, automatic development bootstrap, readiness, feature absence, and owned-resource cleanup'}, indent=2), encoding='utf-8')
    print('PASS source AppHost, development bootstrap, database readiness, and UUID-owned cleanup')
    print('Evidence:', artifacts.relative_to(ROOT))
